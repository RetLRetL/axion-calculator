// ===== interpolate =====
double interpolate(const vector<double>& E, const vector<double>& S, double x)
{
    if (x <= E.front()) return S.front();
    if (x >= E.back())  return S.back();

    for (size_t i = 0; i < E.size()-1; i++)
    {
        if (x >= E[i] && x < E[i+1])
        {
            double t = (x - E[i]) / (E[i+1] - E[i]);
            return S[i] + t * (S[i+1] - S[i]);
        }
    }
    return 0.0;
}

