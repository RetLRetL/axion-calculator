double sigma_SM_mix(double E)
{
    const double Z = 92.0;

    double sum_n = 0.0;
    double sum_n_sigma = 0.0;
    //double sum_nA = 0.0;

    for (auto &el : mixture)
    {
        if (E_data.find(el.name) == E_data.end() || E_data[el.name].empty()) {
            cout << "NO DATA FOR: " << el.name << endl;
            continue;
        }

        double sigma_i = interpolate(E_data[el.name], S_data[el.name], E);

        sum_n += el.n;
        sum_n_sigma += el.n * sigma_i;
        //sum_nA += el.n * el.A;
    }

    if (sum_n < 1e-30) return 1e-30;

    //double A_eff = sum_nA / sum_n;
    double result = /*(A_eff / (NA * Z)) * */ (sum_n_sigma / sum_n);
    
    if (result < 1e-30) result = 1e-30;
    
    return result;
}